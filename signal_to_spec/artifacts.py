"""Turn scored themes into things a team can act on: a PRD draft, a Jira backlog, a CSV."""

from __future__ import annotations

import csv
from datetime import date
from pathlib import Path

import pandas as pd

from .themes import Theme

PRIORITY_BY_RANK = {1: "Highest", 2: "Highest", 3: "High", 4: "High", 5: "Medium", 6: "Medium"}


def _fmt_mix(mix: dict) -> str:
    return " · ".join(f"{k} {v}" for k, v in sorted(mix.items(), key=lambda kv: -kv[1]))


def _quote_line(row: pd.Series) -> str:
    return f"> “{row['clean_text']}”  \n> — {row['segment']} customer · {row['source']} · {row['date']:%b %d}"


def _top_accounts(items: pd.DataFrame, n: int = 5) -> list[str]:
    by_acct = items.groupby(["account", "segment"])["seats"].max().sort_values(ascending=False)
    return [f"{acct} ({seg}, {seats:,} seats)" for (acct, seg), seats in by_acct.head(n).items()]


def write_opportunities_csv(scored: pd.DataFrame, path: Path) -> None:
    out = scored.copy()
    out["segment_mix"] = out["segment_mix"].map(_fmt_mix)
    out["source_mix"] = out["source_mix"].map(_fmt_mix)
    out = out.drop(columns=["weekly"])
    out.to_csv(path, index=False)


def _summary(theme: Theme, row: pd.Series) -> str:
    return theme.problem or (
        f"{row['accounts']} accounts ({row['seats_affected']:,} seats) raised this {row['mentions']} times "
        f"across {len(row['source_mix'])} channels. {row['urgency']:.0%} of mentions carry urgency signals "
        f"(blocked work, churn risk or willingness to pay)."
    )


def build_prd(theme: Theme, row: pd.Series, df: pd.DataFrame, n_ranked: int, llm_sections: dict | None) -> str:
    items = df.iloc[theme.member_index].sort_values("date")
    quotes = df.iloc[theme.representative_index]
    momentum = f"{row['momentum_pct']:+d}%" if row["prior_4w"] else "new in the last 4 weeks"
    effort = (
        f"{row['effort_weeks']:g} engineer-weeks (from the team review file) → RICE {row['rice']:g}"
        if pd.notna(row["effort_weeks"])
        else "Not estimated yet. Run the spike in the Jira backlog, then re-run with `--review`."
    )
    tldr = _summary(theme, row)
    score = f"RICE {row['rice']:g}" if pd.notna(row["rice"]) else f"opportunity score {row['opportunity_score']:g}"

    lines = [
        f"# PRD (draft): {theme.display_name}",
        "",
        f"_Generated by signal-to-spec on {date.today():%b %d, %Y} from {len(df)} problem-related feedback items. "
        "This is a starting draft for discussion with design and engineering, not a commitment._",
        "",
        "## TL;DR",
        "",
        tldr,
        "",
        "## Evidence",
        "",
        "| Signal | Value |",
        "|---|---|",
        f"| Priority rank | #{row['rank']} of {n_ranked} themes ({score}) |",
        f"| Mentions / accounts | {row['mentions']} mentions from {row['accounts']} accounts |",
        f"| Seats behind those accounts | {row['seats_affected']:,} |",
        f"| Segments | {_fmt_mix(row['segment_mix'])} |",
        f"| Channels | {_fmt_mix(row['source_mix'])} |",
        f"| Trend (last 4 weeks vs prior 4) | {momentum} ({row['last_4w']} vs {row['prior_4w']}) |",
        f"| Average sentiment (−1 to +1) | {row['avg_sentiment']:+.2f} |",
        f"| Urgency signals | {row['urgency']:.0%} of mentions |",
        f"| RICE inputs | Reach {row['reach']:g} · Impact {row['impact']:g} · Confidence {row['confidence']:.0%} |",
        "",
        "### In customers' words",
        "",
    ]
    for _, q in quotes.iterrows():
        lines += [_quote_line(q), ""]

    lines += [
        "## Who is affected",
        "",
        f"Most mentions come from **{max(row['segment_mix'], key=row['segment_mix'].get)}** accounts. "
        "Largest accounts raising it:",
        "",
        *[f"- {a}" for a in _top_accounts(items)],
        "",
        "## Goals and success metrics",
        "",
        f"- **Outcome:** cut new feedback on this theme by 50% within two releases of shipping "
        f"(baseline: {row['last_4w']} mentions in the last 4 weeks).",
        f"- **Sentiment:** lift average sentiment on related feedback from {row['avg_sentiment']:+.2f} to above +0.20.",
        "- **Leading indicator:** agree one in-product metric with engineering and data before build starts "
        "(see the instrumentation task in the backlog).",
        "",
        "## User stories",
        "",
    ]
    if llm_sections and llm_sections.get("user_stories"):
        for s in llm_sections["user_stories"]:
            lines.append(f"- **{s.get('story', '').strip()}**")
            for ac in s.get("acceptance_criteria", []):
                lines.append(f"  - [ ] {ac}")
        lines.append("")
    else:
        lines += [
            "_To write with design and engineering after discovery interviews. "
            "Run with `--llm` to get a first draft grounded in the quotes above._",
            "",
        ]

    lines += ["## Engineering perspective", "", f"- **Effort:** {effort}", "- **Dependencies:** to confirm in the spike.", ""]

    lines += ["## Risks", ""]
    risks = (llm_sections or {}).get("risks") or [
        "The theme may bundle several distinct problems. Confirm in interviews before scoping.",
        "Feedback over-represents vocal channels; check the problem against usage data.",
    ]
    lines += [f"- {r}" for r in risks] + [""]

    lines += ["## Open questions", ""]
    questions = (llm_sections or {}).get("open_questions") or [
        "What does “fixed” look like to the accounts above, in their own words?",
        "Which segment do we solve for first, and what do we deliberately leave out?",
        "Is there a quick mitigation we can ship while the full fix is built?",
    ]
    lines += [f"- {q}" for q in questions] + [""]

    lines += [
        "## Appendix: all feedback in this theme",
        "",
        "| Date | Segment | Channel | Feedback |",
        "|---|---|---|---|",
    ]
    for _, r in items.head(60).iterrows():
        text = r["clean_text"].replace("|", "\\|")
        lines.append(f"| {r['date']:%Y-%m-%d} | {r['segment']} | {r['source']} | {text} |")
    return "\n".join(lines) + "\n"


def build_jira_rows(
    ranked_themes: list[tuple[Theme, pd.Series]], df: pd.DataFrame, llm_by_theme: dict[int, dict]
) -> list[dict]:
    """Epics with child issues, in a shape Jira's CSV importer can map (Issue Id / Parent Id)."""
    rows: list[dict] = []
    next_id = 1
    for theme, row in ranked_themes:
        items = df.iloc[theme.member_index]
        priority = PRIORITY_BY_RANK.get(int(row["rank"]), "Low")
        epic_id = next_id
        next_id += 1
        labels = ["voice-of-customer", "signal-to-spec"]
        rows.append(
            {
                "Issue Id": epic_id,
                "Parent Id": "",
                "Issue Type": "Epic",
                "Summary": theme.display_name[:250],
                "Description": (
                    f"{_summary(theme, row)}\n\n"
                    f"Rank #{row['rank']} · opportunity score {row['opportunity_score']:g} · "
                    f"{row['mentions']} mentions from {row['accounts']} accounts ({row['seats_affected']:,} seats) · "
                    f"trend {row['momentum_pct']:+d}% vs prior 4 weeks.\n"
                    f"Segments: {_fmt_mix(row['segment_mix'])}"
                ),
                "Priority": priority,
                "Labels": labels,
            }
        )
        children = [
            (
                "Task",
                f"Discovery: interview 5 accounts about {theme.display_name}",
                "Validate the problem and what 'fixed' means. Start with: " + "; ".join(_top_accounts(items)),
            ),
            (
                "Task",
                f"Spike: solution options and effort for {theme.display_name}",
                "Engineering estimate in person-weeks. Add it to the team review file and re-run with --review to get a full RICE score.",
            ),
            (
                "Task",
                f"Instrument: baseline metric for {theme.display_name}",
                "Agree one in-product metric that moves if this is solved, and capture a baseline before build.",
            ),
        ]
        for story in (llm_by_theme.get(theme.theme_id) or {}).get("user_stories", []):
            ac = "\n".join(f"- {a}" for a in story.get("acceptance_criteria", []))
            children.append(("Story", story.get("story", "")[:250], f"Acceptance criteria:\n{ac}"))
        for issue_type, summary, description in children:
            rows.append(
                {
                    "Issue Id": next_id,
                    "Parent Id": epic_id,
                    "Issue Type": issue_type,
                    "Summary": summary,
                    "Description": description,
                    "Priority": priority,
                    "Labels": labels,
                }
            )
            next_id += 1
    return rows


def write_jira_csv(rows: list[dict], path: Path) -> None:
    """Jira labels can't contain spaces, so each label gets its own repeated "Labels" column."""
    fields = ["Issue Id", "Parent Id", "Issue Type", "Summary", "Description", "Priority"]
    n_labels = max((len(r["Labels"]) for r in rows), default=0)
    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(fields + ["Labels"] * n_labels)
        for r in rows:
            labels = list(r["Labels"]) + [""] * (n_labels - len(r["Labels"]))
            writer.writerow([r[k] for k in fields] + labels)
